"""Controlled synthetic workload scenarios from the research design.

Each scenario is a non-homogeneous Poisson process per tier (generated by
thinning) with the same service-time, CPU and penalty model as
``traffic.generate_requests``. Bursts are either periodic (forecastable) or at
random start times (unforecastable), which separates a useful forecast from a
policy change that merely happens to help.
"""

from dataclasses import dataclass, field
import random

from .models import Request
from .traffic import DEFAULT_TIERS, DEFAULT_TIER_WEIGHTS

BASE_SLACK = {"VIP": (0.25, 1.25), "Premium": (0.75, 2.0), "Free": (1.5, 4.0)}
PENALTY = {"VIP": 10.0, "Premium": 4.0, "Free": 1.0}
BURST_PERIOD = 60.0
BURST_LENGTH = 15.0


@dataclass(frozen=True)
class Scenario:
    name: str
    description: str
    base_rate: float
    burst_multiplier: dict[str, float] = field(default_factory=dict)
    burst_pattern: str = "periodic"  # "periodic" or "random"
    slack_scale: float = 1.0


SCENARIOS: dict[str, Scenario] = {
    s.name: s
    for s in (
        Scenario("normal", "Moderate steady load (rho ~ 0.7)", 4.0),
        Scenario("overload", "Sustained overload (rho ~ 1.15)", 6.5),
        Scenario("vip_spike", "Periodic VIP bursts", 3.4, {"VIP": 6.0}),
        Scenario("free_spike", "Periodic Free-tier bursts", 3.4, {"Free": 4.0}),
        Scenario(
            "mixed_burst", "Periodic bursts on all tiers", 3.2,
            {"VIP": 2.5, "Premium": 2.5, "Free": 2.5},
        ),
        Scenario(
            "random_burst", "Unforecastable bursts on all tiers", 3.2,
            {"VIP": 2.5, "Premium": 2.5, "Free": 2.5}, "random",
        ),
        Scenario("tight_deadlines", "Tight SLA deadlines", 5.0, slack_scale=0.5),
        Scenario("relaxed_deadlines", "Relaxed SLA deadlines", 6.0, slack_scale=3.0),
    )
}


def _in_burst(time: float, pattern: str, random_starts: list[float]) -> bool:
    if pattern == "periodic":
        return (time % BURST_PERIOD) < BURST_LENGTH
    return any(start <= time < start + BURST_LENGTH for start in random_starts)


def generate_scenario(
    name: str, count: int = 1000, seed: int = 42
) -> list[Request]:
    """Generate ``count`` requests for the named scenario, deterministically."""
    if name not in SCENARIOS:
        raise ValueError(f"unknown scenario {name!r}; choose from {sorted(SCENARIOS)}")
    if count < 1:
        raise ValueError("count must be at least 1")
    scenario = SCENARIOS[name]
    rng = random.Random(seed)
    weights = dict(zip(DEFAULT_TIERS, DEFAULT_TIER_WEIGHTS))
    rate_cap = scenario.base_rate * sum(
        weights[t] * max(1.0, scenario.burst_multiplier.get(t, 1.0)) for t in weights
    )

    # Random burst windows, one expected per BURST_PERIOD, over a generous span.
    span = count / scenario.base_rate * 3.0 + BURST_PERIOD
    random_starts: list[float] = []
    cursor = 0.0
    while cursor < span:
        cursor += rng.expovariate(1.0 / BURST_PERIOD)
        random_starts.append(cursor)

    requests: list[Request] = []
    now = 0.0
    while len(requests) < count:
        now += rng.expovariate(rate_cap)
        bursting = _in_burst(now, scenario.burst_pattern, random_starts)
        tier_rates = {
            t: scenario.base_rate
            * weights[t]
            * (scenario.burst_multiplier.get(t, 1.0) if bursting else 1.0)
            for t in weights
        }
        if rng.random() > sum(tier_rates.values()) / rate_cap:
            continue
        tier = rng.choices(list(tier_rates), weights=list(tier_rates.values()), k=1)[0]
        service = rng.uniform(0.05, 0.30)
        slack = rng.uniform(*BASE_SLACK[tier]) * scenario.slack_scale
        requests.append(
            Request(
                request_id=len(requests),
                tier=tier,
                arrival_time=now,
                service_time=service,
                cpu_demand=rng.uniform(10.0, 60.0),
                deadline=now + slack,
                sla_penalty=PENALTY[tier],
                endpoint=name,
            )
        )
    return requests
